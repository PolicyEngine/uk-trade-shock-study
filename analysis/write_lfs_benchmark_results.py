"""Generate manuscript macros and table rows from LFS benchmark artifacts."""

from __future__ import annotations

import json
from pathlib import Path

import numpy as np
import pandas as pd


ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "results/lfs_qrf_benchmark.csv.gz"
DIAGNOSTICS = ROOT / "results/lfs_qrf_benchmark.diagnostics.json"
OUTPUT = ROOT / "paper/generated_lfs_benchmarks.tex"


def weighted_quantile(values, weights, quantiles=(0.1, 0.5, 0.9)):
    order = np.argsort(values)
    values = np.asarray(values)[order]
    weights = np.asarray(weights)[order]
    cumulative = np.cumsum(weights) - weights / 2
    cumulative /= weights.sum()
    return np.interp(quantiles, cumulative, values)


def row(label: str, values: pd.Series, weights: pd.Series) -> str:
    valid = values.notna() & weights.gt(0)
    mean = np.average(values[valid], weights=weights[valid])
    q10, q50, q90 = weighted_quantile(values[valid], weights[valid])
    return (
        f"{label} & {100 * mean:.2f} & {100 * q10:.2f} & "
        f"{100 * q50:.2f} & {100 * q90:.2f} \\\\"
    )


def main() -> None:
    data = pd.read_csv(DATA)
    diagnostics = json.loads(DIAGNOSTICS.read_text())
    rows = [
        row("Calibrated SIC--sex--age cells", data["job_exit_probability"], data["weight"]),
        row(
            "Calibrated income terciles",
            data["job_exit_probability_banded"],
            data["weight"],
        ),
        row(
            "Regularised QRF benchmark",
            data["qrf_job_exit_calibrated"],
            data["weight"],
        ),
    ]
    content = "\n".join(
        [
            "% Generated by analysis/write_lfs_benchmark_results.py",
            f"\\newcommand{{\\LFSExitTarget}}{{{100 * diagnostics['job_exit_target']:.2f}}}",
            f"\\newcommand{{\\LFSWageTarget}}{{{100 * diagnostics['wage_change_target']:.2f}}}",
            f"\\newcommand{{\\LFSManufacturingDonors}}{{{diagnostics['manufacturing_target_donors']}}}",
            f"\\newcommand{{\\LFSAllDonors}}{{{diagnostics['lfs_all_employed_donors']}}}",
            f"\\newcommand{{\\LFSWageDonors}}{{{diagnostics['lfs_wage_training_donors']}}}",
            f"\\newcommand{{\\LFSFRSReceivers}}{{{diagnostics['frs_receivers']}}}",
            f"\\newcommand{{\\LFSExitCorrelation}}{{{diagnostics['cell_qrf_exit_correlation']:.2f}}}",
            f"\\newcommand{{\\LFSWageCorrelation}}{{{diagnostics['cell_qrf_wage_correlation']:.2f}}}",
            f"\\newcommand{{\\LFSQRFExitMaximum}}{{{100 * diagnostics['qrf_exit_range'][1]:.1f}}}",
            f"\\newcommand{{\\LFSQRFWageMinimum}}{{{100 * diagnostics['qrf_wage_change_range'][0]:.1f}}}",
            f"\\newcommand{{\\LFSQRFWageMaximum}}{{{100 * diagnostics['qrf_wage_change_range'][1]:.1f}}}",
            "\\newcommand{\\LFSBenchmarkRows}{%",
            *rows,
            "}",
            "",
        ]
    )
    OUTPUT.write_text(content)
    print(f"Wrote {OUTPUT}")


if __name__ == "__main__":
    main()
