"""Emit descriptive macros about the Microcosm UK dataset the paper quotes.

Reads the certified file's household table (aggregates only) and writes
results/generated_data.tex, copied to paper/.

Run:  python analysis/emit_data_macros.py
"""

import shutil
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parent.parent


def main() -> None:
    from uk_trade_shock_study.microcosm import dataset_path

    h = pd.read_hdf(dataset_path(), "household")
    w = h["household_weight"].astype(float)
    syn = h["household_is_spi_synthetic"].astype(bool)
    m = {
        "DataSyntheticWeightPct": f"{100 * w[syn].sum() / w.sum():.0f}",
        "DataSyntheticRecords": f"{int(syn.sum()):,}",
        "DataSourceHouseholds": f"{h['source_household_id'].nunique():,}",
        "DataHouseholdRecords": f"{len(h):,}",
    }
    lines = ["% Generated by analysis/emit_data_macros.py -- do not edit."]
    lines += [f"\\newcommand{{\\{k}}}{{{v}}}" for k, v in m.items()]
    out = ROOT / "results" / "generated_data.tex"
    out.write_text("\n".join(lines) + "\n")
    shutil.copy(out, ROOT / "paper" / "generated_data.tex")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
