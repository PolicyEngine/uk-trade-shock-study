"""Emit LaTeX macros for poverty CONDITIONAL ON BEING AFFECTED.

WHY THIS EXISTS (referee point on the welfare-relevant statistic). The
manuscript reports the NATIONAL poverty change, which is near-null by
construction: about ten FRS records lose their earnings in a 68-million-person
population, so no national headcount can move. results/poverty_gap.json
already carries the statistic that does move — the poverty rate among people
in AFFECTED households, which rises from roughly 5 per cent at baseline to
roughly 31 per cent under displacement — and nothing in the paper reports it.

These macros make that number quotable without hand-typing it, and refuse to
emit it when the artifact behind it is too thin to support a claim: the
5-draw exploratory artifact has an assignment SD of about 30 points on a
26-point change, so the writer HARD-FAILS below ``--min-draws`` (default 50,
the submission design) and names the make target that rebuilds it.

Reads results/poverty_gap.json, writes paper/generated_welfare.tex.

Usage: .venv/bin/python analysis/write_welfare_results.py [--min-draws 50]
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

#: Make target that rebuilds the artifact at the production draw count. Named
#: in the failure message: a writer that just says "too few draws" leaves the
#: reader to guess how to fix it.
PRODUCTION_TARGET = "make poverty-gap-production"

#: (artifact key, macro infix) for the margins reported. The wage-cut margin
#: is a single deterministic run (see analysis/poverty_gap.py), so it has no
#: assignment SD; SD macros are emitted for it only if the artifact ever
#: carries repeated wage-cut draws.
MARGINS = (
    ("full_tariff_displacement", "Disp"),
    ("epd_displacement", "EPD"),
    ("full_tariff_wage_cut", "Wage"),
)


def fmt(value: float, digits: int = 1) -> str:
    return f"{value:.{digits}f}"


def stat(entry: dict, key: str) -> tuple[float, float | None]:
    """Value and SD for one field, across both artifact shapes.

    Monte Carlo margins store ``{"mean": ..., "sd": ...}``; the deterministic
    wage-cut margin stores a bare number and has no SD.
    """
    if key not in entry:
        raise KeyError(f"poverty_gap artifact is missing {key!r}")
    value = entry[key]
    if isinstance(value, dict):
        return float(value["mean"]), float(value["sd"])
    return float(value), None


def build_macros(artifact: dict, min_draws: int) -> dict[str, str]:
    n_draws = int(artifact["n_draws"])
    if n_draws < min_draws:
        raise ValueError(
            f"results/poverty_gap.json has {n_draws} draws, below the "
            f"--min-draws threshold of {min_draws}. The affected-household "
            "poverty rate is not reportable at that sample size (its "
            "assignment SD is of the same order as the change itself). "
            f"Rebuild the artifact with `{PRODUCTION_TARGET}` before "
            "generating welfare macros."
        )
    macros = {
        "WelfarePovDraws": str(n_draws),
        "WelfareWageDraws": str(int(artifact.get("wage_cut_n_draws", 1))),
    }
    for key, infix in MARGINS:
        entry = artifact[key]
        fields = (
            ("affected_pov_rate_baseline", "PovBase", 100.0, 1),
            ("affected_pov_rate_shocked", "PovShock", 100.0, 1),
            ("affected_pov_rate_change_pp", "PovChange", 1.0, 1),
            # weighted people in affected households, THOUSANDS
            ("affected_people_weighted", "People", 1e-3, 1),
        )
        for field, suffix, scale, digits in fields:
            value, sd = stat(entry, field)
            macros[f"Welfare{infix}{suffix}"] = fmt(value * scale, digits)
            if sd is not None:
                macros[f"Welfare{infix}{suffix}SD"] = fmt(sd * scale, digits)
    return macros


def parse_args(argv=None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--poverty-gap", type=Path, default=Path("results/poverty_gap.json")
    )
    parser.add_argument(
        "--output", type=Path, default=Path("paper/generated_welfare.tex")
    )
    parser.add_argument(
        "--min-draws",
        type=int,
        default=50,
        help="refuse to emit macros from an artifact with fewer draws",
    )
    return parser.parse_args(argv)


def main(argv=None) -> None:
    args = parse_args(argv)
    artifact = json.loads(args.poverty_gap.read_text())
    macros = build_macros(artifact, args.min_draws)
    lines = [
        "% Generated by analysis/write_welfare_results.py; do not edit.",
        "% Poverty among people in AFFECTED households (those containing a",
        "% displaced worker, or any worker whose earnings fall on the",
        "% wage-cut margin). Rates and SDs are PER CENT; PovChange is in",
        "% percentage points; People and its SD are THOUSANDS of people.",
        "% SDs are across assignment draws; the wage-cut margin is a single",
        "% deterministic run and therefore has no SD macros.",
        *(f"\\newcommand{{\\{key}}}{{{value}}}" for key, value in macros.items()),
    ]
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text("\n".join(lines) + "\n")
    print(f"Wrote {args.output} ({len(macros)} macros)")


if __name__ == "__main__":
    main()
