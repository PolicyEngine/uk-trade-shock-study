"""Unit tests for the conditional-on-affected welfare macro writer.

Synthetic poverty_gap artifacts only: no FRS microdata and no
policyengine-uk are involved.
"""

import json
import re

import pytest

from analysis.write_welfare_results import (
    MARGINS,
    PRODUCTION_TARGET,
    build_macros,
    main,
)


def margin_entry(baseline, shocked, people, sd=None):
    fields = {
        "affected_pov_rate_baseline": baseline,
        "affected_pov_rate_shocked": shocked,
        "affected_pov_rate_change_pp": 100 * (shocked - baseline),
        "affected_people_weighted": people,
    }
    if sd is None:
        return fields
    return {key: {"mean": value, "sd": sd[key]} for key, value in fields.items()}


def make_artifact(n_draws=50):
    sd = {
        "affected_pov_rate_baseline": 0.02,
        "affected_pov_rate_shocked": 0.08,
        "affected_pov_rate_change_pp": 7.5,
        "affected_people_weighted": 9_000.0,
    }
    return {
        "n_draws": n_draws,
        "wage_cut_n_draws": 1,
        "full_tariff_displacement": margin_entry(0.05, 0.313, 39_661.0, sd),
        "epd_displacement": margin_entry(0.0506, 0.3048, 33_700.0, sd),
        # deterministic single run: bare numbers, no SDs
        "full_tariff_wage_cut": margin_entry(0.043, 0.043, 4_626_000.0),
    }


def write_artifact(tmp_path, artifact):
    path = tmp_path / "poverty_gap.json"
    path.write_text(json.dumps(artifact))
    return path


def test_macros_carry_the_affected_household_poverty_rates():
    macros = build_macros(make_artifact(), min_draws=50)
    assert macros["WelfarePovDraws"] == "50"
    assert macros["WelfareDispPovBase"] == "5.0"
    assert macros["WelfareDispPovShock"] == "31.3"
    assert macros["WelfareDispPovChange"] == "26.3"
    assert macros["WelfareDispPovShockSD"] == "8.0"
    assert macros["WelfareEPDPovShock"] == "30.5"
    # people are emitted in THOUSANDS
    assert macros["WelfareDispPeople"] == "39.7"
    assert macros["WelfareWagePeople"] == "4626.0"


def test_deterministic_wage_cut_margin_gets_no_sd_macros():
    macros = build_macros(make_artifact(), min_draws=50)
    assert macros["WelfareWageDraws"] == "1"
    assert not [key for key in macros if key.startswith("WelfareWage") and key.endswith("SD")]
    # ... while the Monte Carlo margins do carry them
    assert "WelfareDispPovChangeSD" in macros
    assert "WelfareEPDPeopleSD" in macros


def test_every_declared_margin_is_covered():
    macros = build_macros(make_artifact(), min_draws=50)
    for _, infix in MARGINS:
        for suffix in ("PovBase", "PovShock", "PovChange", "People"):
            assert f"Welfare{infix}{suffix}" in macros


def test_thin_artifact_hard_fails_and_names_the_make_target():
    with pytest.raises(ValueError) as excinfo:
        build_macros(make_artifact(n_draws=5), min_draws=50)
    message = str(excinfo.value)
    assert "5 draws" in message
    assert PRODUCTION_TARGET in message


def test_threshold_is_configurable_but_still_binding():
    build_macros(make_artifact(n_draws=20), min_draws=20)
    with pytest.raises(ValueError):
        build_macros(make_artifact(n_draws=20), min_draws=21)


def test_missing_field_is_reported_rather_than_silently_skipped():
    artifact = make_artifact()
    del artifact["full_tariff_displacement"]["affected_pov_rate_shocked"]
    with pytest.raises(KeyError, match="affected_pov_rate_shocked"):
        build_macros(artifact, min_draws=50)


def test_main_writes_a_latex_macro_file(tmp_path):
    path = write_artifact(tmp_path, make_artifact())
    output = tmp_path / "generated_welfare.tex"
    main(["--poverty-gap", str(path), "--output", str(output)])
    text = output.read_text()
    assert text.startswith("% Generated by analysis/write_welfare_results.py")
    defined = set(re.findall(r"\\newcommand\{\\(\w+)\}", text))
    assert {"WelfareDispPovShock", "WelfarePovDraws", "WelfareWagePeople"} <= defined
    assert all(name.startswith("Welfare") for name in defined)


def test_poverty_gap_draw_count_is_a_command_line_parameter():
    """`make poverty-gap-production` depends on this flag existing."""
    from analysis.poverty_gap import N_DRAWS, parse_args

    assert parse_args([]).n_draws == N_DRAWS
    assert parse_args(["--n-draws", "50"]).n_draws == 50
    with pytest.raises(SystemExit):
        parse_args(["--n-draws", "0"])


def test_main_refuses_to_write_from_a_thin_artifact(tmp_path):
    path = write_artifact(tmp_path, make_artifact(n_draws=5))
    output = tmp_path / "generated_welfare.tex"
    with pytest.raises(ValueError, match=re.escape(PRODUCTION_TARGET)):
        main(["--poverty-gap", str(path), "--output", str(output)])
    assert not output.exists()
