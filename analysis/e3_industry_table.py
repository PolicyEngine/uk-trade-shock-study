"""Industry table for the tariff episode (E3).

One row per exposed SIC 2007 division, sorted by its gross earnings loss:
the US tariff rate, US exports as a share of the division's turnover, the
sector shock s_j (tariff x export share x elasticity x incidence), weighted
employees, mean earnings and the gross earnings loss in the model, and the
division's share of the total loss. The TOP_ROWS largest are shown; the rest
are pooled in an "other" row (employee-weighted rate, share and shock).

Reads results/e3_ashe.json (analysis/ashe_validation.py), which holds the
model's per-division employees, wage bill and shock at the simulation year,
so no simulation is run here. Writes results/table_e3_industry.tex (copied
to paper/) and results/e3_industry.json.

Usage: PYTHONPATH=. .venv/bin/python analysis/e3_industry_table.py
"""

from __future__ import annotations

import json
import shutil
from pathlib import Path

from tariff_pipeline.exposure import (
    DEFAULT_ELASTICITY,
    DEFAULT_WAGE_BILL_INCIDENCE,
    load_us_export_intensity,
    tariff_rates,
)

ROOT = Path(__file__).resolve().parent.parent
RESULTS = ROOT / "results"
TOP_ROWS = 12
#: Short labels for the table (the packaged descriptions are long).
LABELS = {
    10: "Food products", 11: "Beverages", 12: "Tobacco", 13: "Textiles",
    14: "Wearing apparel", 15: "Leather", 16: "Wood products", 17: "Paper",
    18: "Printing", 19: "Coke and refined petroleum", 20: "Chemicals",
    21: "Pharmaceuticals", 22: "Rubber and plastics",
    23: "Non-metallic minerals", 24: "Basic metals (incl. steel)",
    25: "Fabricated metal products", 26: "Computer, electronic, optical",
    27: "Electrical equipment", 28: "Machinery and equipment",
    29: "Motor vehicles", 30: "Other transport (incl. aerospace)",
    31: "Furniture", 32: "Other manufacturing",
}


def build_rows(ashe: dict) -> list[dict]:
    rates = tariff_rates("full_tariff")
    intensity = load_us_export_intensity()["us_export_share"]
    rows = []
    for code, m in ashe["model"]["by_division"].items():
        j = int(code)
        shock = DEFAULT_ELASTICITY * rates[j] * intensity[j] * DEFAULT_WAGE_BILL_INCIDENCE
        if abs(shock - m["shock"]) > 1e-12:
            raise RuntimeError(f"division {j}: shock {m['shock']} is not tariff x share")
        rows.append({
            "division": j,
            "label": LABELS[j],
            "tariff_rate": float(rates[j]),
            "us_export_share": float(intensity[j]),
            "shock": m["shock"],
            "records": m["records"],
            "employees": m["employees"],
            "mean_earnings": m["mean"],
            "gross_loss": m["shock"] * m["wage_bill"],
        })
    total = sum(r["gross_loss"] for r in rows)
    if abs(total / ashe["model"]["overall"]["gross_earnings_loss"] - 1.0) > 1e-9:
        raise RuntimeError("division losses do not sum to the scenario's gross loss")
    for r in rows:
        r["loss_share"] = r["gross_loss"] / total
    return sorted(rows, key=lambda r: -r["gross_loss"])


def pool(rows: list[dict], label: str) -> dict:
    """Aggregate row: employee-weighted rate, export share and shock."""
    employees = sum(r["employees"] for r in rows)
    wavg = lambda key: sum(r[key] * r["employees"] for r in rows) / employees
    return {
        "division": None,
        "label": label,
        "tariff_rate": wavg("tariff_rate"),
        "us_export_share": wavg("us_export_share"),
        "shock": wavg("shock"),
        "records": sum(r["records"] for r in rows),
        "employees": employees,
        "mean_earnings": wavg("mean_earnings"),
        "gross_loss": sum(r["gross_loss"] for r in rows),
        "loss_share": sum(r["loss_share"] for r in rows),
    }


def tex_row(r: dict) -> str:
    code = "" if r["division"] is None else str(r["division"])
    return (
        f"{code} & {r['label']} & {100 * r['tariff_rate']:.0f} & "
        f"{100 * r['us_export_share']:.1f} & {100 * r['shock']:.2f} & "
        f"{r['employees'] / 1e3:,.0f} & {r['mean_earnings'] / 1e3:.1f} & "
        f"{r['gross_loss'] / 1e6:,.0f} & {100 * r['loss_share']:.1f} \\\\"
    )


def main() -> None:
    ashe = json.loads((RESULTS / "e3_ashe.json").read_text())
    rows = build_rows(ashe)
    shown, rest = rows[:TOP_ROWS], rows[TOP_ROWS:]
    other = pool(rest, f"Other {len(rest)} divisions")
    total = pool(rows, f"All {len(rows)} exposed divisions")
    lines = [
        "% Generated by analysis/e3_industry_table.py -- do not edit.",
        "{\\footnotesize",
        "\\begin{tabular}{@{}rlrrrrrrr@{}}",
        "\\toprule",
        "SIC & Division & Tariff & US share & Shock & Employees & Mean pay & Loss & Share \\\\",
        " & & (\\%) & (\\%) & (\\%) & (000) & (\\pounds 000) & (\\pounds m) & (\\%) \\\\",
        "\\midrule",
        *[tex_row(r) for r in shown],
        tex_row(other),
        "\\midrule",
        tex_row(total),
        "\\bottomrule",
        "\\end{tabular}}",
    ]
    out = RESULTS / "table_e3_industry.tex"
    out.write_text("\n".join(lines) + "\n")
    shutil.copy(out, ROOT / "paper" / out.name)
    (RESULTS / "e3_industry.json").write_text(json.dumps(
        {
            "period": ashe["period"],
            "columns": {
                "tariff_rate": "US tariff rate, full-tariff scenario",
                "us_export_share": "US goods exports / division turnover (HMRC 2024 / ABS)",
                "shock": "tariff x US share x elasticity 1 x incidence 1",
                "employees": "weighted persons with positive employment income",
                "mean_earnings": "weighted mean employment income, GBP",
                "gross_loss": "shock x division wage bill, GBP a year",
            },
            "top_rows_shown": TOP_ROWS,
            "rows": rows,
            "other": other,
            "total": total,
            "top3_loss_share": sum(r["loss_share"] for r in rows[:3]),
            "top5_loss_share": sum(r["loss_share"] for r in rows[:5]),
        },
        indent=2,
    ) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
