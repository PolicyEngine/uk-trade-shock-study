"""Robustness: the energy stage with inputs deflated to the rulebook year.

Microcosm UK carries inputs at 2024-25 levels.  The central household stage
copies them unchanged into the back-dated rulebook years (2023-24 rules for
the stage, 2022-23 rules for the cost-of-living payments).  This script
compares that with runs in which every input PolicyEngine UK's own dataset
projection grows is first scaled back to the rulebook year by that
projection's own per-record factor (microcosm.copy_inputs(deflate=True);
survey weights held fixed).

It reads four runs of second_stage_energy.py and emits the comparison:

    second_stage_energy.py                               (central)
    second_stage_energy.py --deflate --out ..._deflated.json
    second_stage_energy.py --sim-year 2022 --out ..._rules2022.json
    second_stage_energy.py --sim-year 2022 --deflate --out ..._rules2022_deflated.json

Run:  python deflated_inputs.py
Emits results/deflated_inputs.json and results/generated_defl.tex (copied
to paper/).
"""

import json
import shutil

from second_stage_energy import PAPER_DIR, RESULTS_DIR

RUNS = {
    "central": "second_stage_energy.json",
    "deflated": "second_stage_energy_deflated.json",
    "rules2022": "second_stage_energy_rules2022.json",
    "rules2022_deflated": "second_stage_energy_rules2022_deflated.json",
}
WORDS = ("One", "Two", "Three", "Four", "Five", "Six", "Seven", "Eight",
         "Nine", "Ten")


def summary(r: dict) -> dict:
    # The Guarantee and Bills Support rates are invariant to the deflation by
    # construction (energy is rebased to a fixed mean and weights are held),
    # so only the full stack and the income-conditioned pieces are compared.
    d, u = r["discretionary"], r["uprating_shortfall"]
    nat = r["automatic_response"]["native_instruments"]
    cush = [x["cushioning_rate_pct"] for x in r["by_decile"]]
    return {
        "full_rate_pct": d["rate_pct_of_counterfactual"],
        "epg_gbp_bn": d["epg_gbp_bn"],
        "col_gbp_bn": d["col_payments_gbp_bn"],
        "discretionary_gbp_bn": d["total_gbp_bn"],
        "benefit_base_gbp_bn": u["benefit_income_base_gbp_bn"],
        "uprating_shortfall_gbp_bn": u["shortfall_gbp_bn"],
        "native_epg_gbp_bn": nat["epg_subsidy"]["baseline_gbp_bn"],
        "native_epg_shocked_gbp_bn": nat["epg_subsidy"]["shocked_gbp_bn"],
        "native_col_gbp_bn": nat["cost_of_living_support_payment"]["baseline_gbp_bn"],
        "automatic_change_gbp_bn": r["automatic_response"]["measured_change_gbp_bn"],
        "cushioning_by_decile_pct": cush,
        "burden_by_decile_pct": [x["burden_pct_of_spending"] for x in r["by_decile"]],
        "within_pct_trimmed": r["variance_decomposition"][
            "expenditure_share_trimmed_1_99"]["within_pct"],
        "energy_rebase_factor": r["meta"]["energy_rebase_factor"],
        "spend_rebase_factor": r["meta"]["spend_rebase_factor"],
    }


def main() -> None:
    runs = {k: json.loads((RESULTS_DIR / f).read_text())
            for k, f in RUNS.items() if (RESULTS_DIR / f).exists()}
    if "deflated" not in runs:
        raise SystemExit("run second_stage_energy.py --deflate first (see docstring)")
    out = {k: summary(r) for k, r in runs.items()}
    c, d = out["central"], out["deflated"]
    diff = [round(b - a, 1) for a, b in zip(c["cushioning_by_decile_pct"],
                                             d["cushioning_by_decile_pct"])]
    out["deflated_minus_central"] = {
        "full_rate_pp": round(d["full_rate_pct"] - c["full_rate_pct"], 1),
        "col_gbp_bn": round(d["col_gbp_bn"] - c["col_gbp_bn"], 2),
        "benefit_base_gbp_bn": round(
            d["benefit_base_gbp_bn"] - c["benefit_base_gbp_bn"], 1),
        "cushioning_by_decile_pp": diff,
        "max_abs_decile_pp": max(abs(x) for x in diff),
    }
    defl_meta = runs["deflated"]["meta"].get("deflation") or {}
    out["deflation_factors_median"] = {
        year: {k: v["scaled"].get(k) for k in (
            "employment_income_before_lsr", "self_employment_income",
            "private_pension_income", "savings_interest_income", "rent",
            "council_tax", "food_and_non_alcoholic_beverages_consumption",
            "domestic_energy_consumption")}
        for year, v in defl_meta.items()}
    out["inputs_scaled"] = {year: len(v["scaled"]) for year, v in defl_meta.items()}
    (RESULTS_DIR / "deflated_inputs.json").write_text(json.dumps(out, indent=1))

    m = ["% generated by deflated_inputs.py -- do not edit by hand."]

    def add(k, v):
        m.append(f"\\newcommand{{\\SsDefl{k}}}{{{v}}}")

    def block(tag, s):
        add(f"{tag}FullRatePct", f"{s['full_rate_pct']:.1f}")
        add(f"{tag}ColBn", f"{s['col_gbp_bn']:,.1f}")
        add(f"{tag}BenefitIncomeBn", f"{s['benefit_base_gbp_bn']:,.1f}")
        add(f"{tag}ShortfallBn", f"{s['uprating_shortfall_gbp_bn']:,.1f}")
        add(f"{tag}NativeEpgBn", f"{s['native_epg_gbp_bn']:,.1f}")
        add(f"{tag}NativeColBn", f"{s['native_col_gbp_bn']:,.1f}")
        add(f"{tag}WithinPct", f"{s['within_pct_trimmed']:.1f}")
        for v, wd in zip(s["cushioning_by_decile_pct"], WORDS):
            add(f"{tag}CushionPctDec{wd}", f"{v:.0f}")

    block("", d)                                   # 2023-24 rules, deflated
    add("FullRateDiffPp", f"{out['deflated_minus_central']['full_rate_pp']:+.1f}")
    add("MaxDecileDiffPp", f"{out['deflated_minus_central']['max_abs_decile_pp']:.1f}")
    add("InputsScaled", f"{max(out['inputs_scaled'].values()) if out['inputs_scaled'] else 0}")
    f23 = out["deflation_factors_median"].get("2023", {})
    f22 = out["deflation_factors_median"].get("2022", {})
    if f23.get("employment_income_before_lsr"):
        add("EarningsFactorTwentyThreePct",
            f"{100 * (f23['employment_income_before_lsr'] - 1):.1f}")
    if f22.get("employment_income_before_lsr"):
        add("EarningsFactorTwentyTwoPct",
            f"{100 * (f22['employment_income_before_lsr'] - 1):.1f}")
    if "rules2022" in out:
        block("RulesTwentyTwoUndeflated", out["rules2022"])
    if "rules2022_deflated" in out:
        block("RulesTwentyTwo", out["rules2022_deflated"])
    path = RESULTS_DIR / "generated_defl.tex"
    path.write_text("\n".join(m) + "\n")
    shutil.copy(path, PAPER_DIR / "generated_defl.tex")
    print(json.dumps({k: v for k, v in out.items()}, indent=1))
    print("wrote", path)


if __name__ == "__main__":
    main()
